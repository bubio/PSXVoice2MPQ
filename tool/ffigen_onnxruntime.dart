// Generates lib/src/third_party/onnxruntime.g.dart from the vendored
// ONNX Runtime C API header.
//
// Run: dart run tool/ffigen_onnxruntime.dart
import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// The C API exports only `OrtGetApiBase`; everything else is reached through
/// the function-pointer tables in `OrtApiBase` / `OrtApi`.
const _functions = {'OrtGetApiBase'};
const _structs = {'OrtApiBase', 'OrtApi'};
const _enums = {
  'ONNXTensorElementDataType',
  'OrtLoggingLevel',
  'OrtErrorCode',
  'GraphOptimizationLevel',
  'OrtAllocatorType',
  'OrtMemType',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = root.resolve('third_party/onnxruntime/onnxruntime_c_api.h');
  await FfiGenerator(
    input: Input(
      entryPoints: [header],
      include: (uri) => uri.path.contains('third_party/onnxruntime/'),
      ignoreSourceErrors: true,
    ),
    visitors: [
      Visitor(
        func: (node) =>
            node.isIncluded = _functions.contains(node.originalName),
        struct: (node) =>
            node.isIncluded = _structs.contains(node.originalName),
        enumClass: (node) =>
            node.isIncluded = _enums.contains(node.originalName),
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/third_party/onnxruntime.g.dart'),
      ),
      // Resolved through the code asset registered in hook/build.dart, whose
      // asset id is this library's URI.
      style: const NativeExternalBindings(),
      preamble: '''
// Copyright (c) Microsoft Corporation. All rights reserved.
// Licensed under the MIT License.
// See third_party/onnxruntime/LICENSE.

// AUTO-GENERATED FILE - DO NOT MODIFY.
// Generated by package:ffigen from third_party/onnxruntime/onnxruntime_c_api.h.
// To regenerate: dart run tool/ffigen_onnxruntime.dart

// ignore_for_file: type=lint, unused_import, unused_element, unused_field
''',
    ),
  ).generate();
  stdout.writeln('Generated lib/src/third_party/onnxruntime.g.dart');
}
